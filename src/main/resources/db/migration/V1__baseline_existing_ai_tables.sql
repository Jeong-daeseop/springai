-- ARCH-0305: 기존에 각 Repository의 @PostConstruct DDL이 만들던 10개 AI_* 테이블을
-- baseline migration으로 표현한다. `docker exec egov-mysql mysqldump --no-data`로 뜬 실제
-- 운영 스키마를 기준으로 작성했다(Java 소스의 DDL 문자열이 아니라 실제 DB가 진실이다).
--
-- 이미 이 테이블들을 가진 기존 DB에서는 spring.flyway.baseline-on-migrate=true +
-- baseline-version=1 설정에 의해 이 파일이 실제로 실행되지 않고 baseline으로만 기록된다.
-- 완전히 새 DB에서는 이 파일이 그대로 실행되어 10개 테이블을 만든다.

CREATE TABLE AI_COMPONENT_REGISTRY (
    PROFILE_ID       VARCHAR(64)  NOT NULL,
    REGISTRY_VERSION VARCHAR(32)  NOT NULL,
    REGISTRY_JSON    LONGTEXT     NOT NULL,
    CREATED_AT       DATETIME(6)  DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (PROFILE_ID, REGISTRY_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_DESIGN_ANALYSIS (
    ANALYSIS_ID    VARCHAR(64)  NOT NULL,
    SOURCE_HASH    VARCHAR(64)  NOT NULL,
    PROVIDER_ID    VARCHAR(32)  NOT NULL,
    MODEL_ID       VARCHAR(100) NOT NULL,
    PROMPT_VERSION VARCHAR(32)  NOT NULL,
    RESULT_JSON    LONGTEXT     NOT NULL,
    CREATED_AT     DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ANALYSIS_ID),
    UNIQUE KEY UK_DESIGN_ANALYSIS_CACHE (SOURCE_HASH, PROVIDER_ID, MODEL_ID, PROMPT_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_DESIGN_SYSTEM_PROFILE (
    PROFILE_ID      VARCHAR(64) NOT NULL,
    PROFILE_VERSION VARCHAR(32) NOT NULL,
    PROFILE_STATUS  VARCHAR(32) NOT NULL,
    PROFILE_JSON    LONGTEXT    NOT NULL,
    CREATED_AT      DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_AT      DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (PROFILE_ID, PROFILE_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_FIGMA_DESIGN_OPERATION (
    OPERATION_ID   VARCHAR(64) NOT NULL,
    REVISION       INT         NOT NULL,
    STATUS         VARCHAR(32) NOT NULL,
    OPERATION_JSON LONGTEXT    NOT NULL,
    CREATED_AT     DATETIME    DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (OPERATION_ID, REVISION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_FIGMA_DESIGN_OPERATION_IDEMPOTENCY (
    REQUEST_HASH VARCHAR(128) NOT NULL,
    OPERATION_ID VARCHAR(64)  NOT NULL,
    CREATED_AT   DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (REQUEST_HASH)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_FIGMA_GENERATION_REPORT (
    REPORT_ID      VARCHAR(64) NOT NULL,
    SCREEN_ID      VARCHAR(64) NOT NULL,
    SCREEN_VERSION INT         NOT NULL,
    SUCCESS_YN     CHAR(1)     NOT NULL,
    REPORT_JSON    LONGTEXT    NOT NULL,
    CREATED_AT     DATETIME    DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (REPORT_ID),
    KEY IDX_FIGMA_REPORT_SCREEN (SCREEN_ID, SCREEN_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_FIGMA_REVIEW_HISTORY (
    EVENT_ID       VARCHAR(64)   NOT NULL,
    TARGET_TYPE    VARCHAR(32)   NOT NULL,
    TARGET_ID      VARCHAR(64)   NOT NULL,
    TARGET_VERSION VARCHAR(32)   NOT NULL,
    EVENT_TYPE     VARCHAR(32)   NOT NULL,
    EVENT_STATUS   VARCHAR(64)   DEFAULT NULL,
    ACTOR          VARCHAR(128)  DEFAULT NULL,
    COMMENT_TEXT   VARCHAR(2000) DEFAULT NULL,
    OCCURRED_AT    DATETIME      DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EVENT_ID),
    KEY IDX_FIGMA_REVIEW_HISTORY_TARGET (TARGET_TYPE, TARGET_ID, TARGET_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_FIGMA_SCREEN_SPEC (
    SCREEN_ID           VARCHAR(64) NOT NULL,
    SCREEN_VERSION       INT         NOT NULL,
    SCREEN_SPEC_ID       VARCHAR(64) NOT NULL,
    SCREEN_SPEC_VERSION  INT         NOT NULL,
    SPEC_JSON            LONGTEXT    NOT NULL,
    CREATED_AT           DATETIME    DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (SCREEN_ID, SCREEN_VERSION),
    KEY IDX_FIGMA_SCREEN_SPEC_SOURCE (SCREEN_SPEC_ID, SCREEN_SPEC_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_GENERATION_HISTORY (
    ID              BIGINT       NOT NULL AUTO_INCREMENT,
    TABLE_NAME      VARCHAR(100) NOT NULL,
    DOMAIN          VARCHAR(100) NOT NULL,
    PACKAGE_NAME    VARCHAR(200) DEFAULT NULL,
    OUTPUT_PATH     VARCHAR(500) DEFAULT NULL,
    GENERATED_FILES TEXT,
    CREATED_AT      DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_SCREEN_SPECIFICATION (
    SPEC_ID       VARCHAR(64)  NOT NULL,
    SPEC_VERSION  INT          NOT NULL,
    SPEC_STATUS   VARCHAR(32)  NOT NULL,
    DATABASE_NAME VARCHAR(100) NOT NULL,
    PRIMARY_TABLE VARCHAR(128) NOT NULL,
    SPEC_JSON     LONGTEXT     NOT NULL,
    CREATED_AT    DATETIME     DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (SPEC_ID, SPEC_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
